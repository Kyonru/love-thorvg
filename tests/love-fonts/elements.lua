return function(thorvg)
  assert(thorvg.capabilities.svgElements)
  assert(love.filesystem.write('elements.svg', '<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 40 40"><g id="box"><rect x="2" y="3" width="8" height="6" fill="red"/></g></svg>'))
  local doc = thorvg.new('elements.svg', {autoplay = false})
  local x,y,w,h = doc:getElementBounds('box')
  assert(x == 2 and y == 3 and w == 8 and h == 6)
  local pixels = doc:getImageData()
  local texture = doc:getImage()
  local _,_,_,alpha = pixels:getPixel(5,5)
  assert(alpha == 1)
  doc:setElement('box', {1,0,0,1,15,0}, .5)
  assert(doc:getImageData() == pixels and doc:getImage() == texture, 'edit reallocated targets')
  local _,_,_,old = pixels:getPixel(5,5)
  local _,_,_,moved = pixels:getPixel(20,5)
  assert(old == 0 and math.abs(moved-.5) < .01)
  assert(not pcall(doc.setElement, doc, 'missing', {1,0,0,1,0,0}))
  assert(not pcall(doc.setElement, doc, 'box', {0/0,0,0,1,0,0}))
  doc:release()
  assert(not pcall(doc.getElementBounds, doc, 'box'))
  local cached = thorvg.new('elements.svg', {frameCache = 2})
  cached:render()
  assert(cached:getCacheStats().size == 1)
  cached:setElement('box', {1,0,0,1,15,0}, 1)
  assert(cached:getCacheStats().size == 0)
  cached:render()
  assert(not cached:getRenderStats().lastCacheHit)
  cached:release()
  love.filesystem.remove('elements.svg')
  print('PASS: LÖVE SVG element edits, texture reuse, bounds, cache invalidation and lifecycle')
end
